const ALLOWED_TYPES = ['QT', 'ANNEXA', 'PI', 'OC', 'BUYERPO', 'SUPPO', 'FDN', 'PL', 'BLI', 'CI', 'COOPREP'];

/**
 * The invoice date staff picked: null for today (left blank or today), the
 * YYYY-MM-DD date for an earlier day, or false when it is not a real date,
 * is in the future, or is before the order was created.
 */
async function pickedDocumentDate(date, orderId) {
  const value = date.trim();
  const today = todayIst();
  if (value === '' || value === today) return null;
  const m = value.match(/^(\d{4})-(\d{2})-(\d{2})$/);
  if (!m) return false;
  const d = new Date(`${value}T00:00:00Z`);
  if (Number.isNaN(d.getTime()) || d.getUTCFullYear() !== Number(m[1]) || d.getUTCMonth() + 1 !== Number(m[2]) || d.getUTCDate() !== Number(m[3]) || value > today) return false;
  const order = await orderRepository.find(orderId);
  if (order && order.created_at && value < String(order.created_at).slice(0, 10)) return false;
  return value;
}

/**
 * QA Round 6, R6-N18: one generation per order and document type at a time —
 * a MySQL named lock held on its own pool connection (a named lock belongs to
 * one connection), so of several posts at the same moment only the first
 * makes a revision. Port of DocumentController::claimGeneration().
 *
 * @returns {Promise<{release: function(): Promise<void>}|null>} null when another request holds it
 */
async function claimGeneration(orderId, type) {
  const name = `nx_docgen_${orderId}_${type}`;
  const conn = await db.pool.getConnection();
  try {
    const [[row]] = await conn.query('SELECT GET_LOCK(?, 0) AS got', [name]);
    if (Number(row.got) !== 1) {
      conn.release();
      return null;
    }
  } catch (err) {
    conn.release();
    throw err;
  }
  return {
    async release() {
      try {
        await conn.query('SELECT RELEASE_LOCK(?)', [name]);
      } finally {
        conn.release();
      }
    },
  };
}

async function generate(req, res) {
  const orderId = parseInt(req.params.id, 10);
  const type = String(req.body.document_type || '').toUpperCase();
  const user = req.user;

  if (!ALLOWED_TYPES.includes(type)) {
    flash.set(req, 'error', `Unknown or unsupported document type: ${type}`);
    res.redirect(`/orders/${orderId}`);
    return;
  }
  // Owner decision D-214, phase 2: nobody generates a document carrying money their department may not see.
  if (!moneyVisibility.canSeeDocument(req.permissions, type)) {
    flash.set(req, 'error', `The ${type} carries prices your department does not see — it is generated by the department that owns them.`);
    res.redirect(`/orders/${orderId}`);
    return;
  }

  // QA Round 5, R5-03: terms needing MD/ED approval block the Quotation.
  if (type === 'QT' && (await paymentTermsApprovalService.isPending(orderId))) {
    flash.set(req, 'error', await paymentTermsApprovalService.pendingMessage(orderId));
    res.redirect(`/orders/${orderId}#step-1-quotation-prepare`);
    return;
  }

  // PDF is always generated — the approval workflow, the draft->final
  // watermark swap, and the buyer email attachment all assume every
  // document has one, so it isn't actually a user-controllable choice even
  // though the PDF checkbox is shown (checked, disabled) for clarity in the
  // form. DOCX is the real optional toggle.
  const generateDocx = !!req.body.generate_docx;

  // Owner request (2026-10-27): the Commercial Invoice can be dated today or
  // earlier (e.g. to match the BL) — today if left blank.
  let documentDate = null;
  if (type === 'CI') {
    documentDate = await pickedDocumentDate(String(req.body.document_date || ''), orderId);
    if (documentDate === false) {
      flash.set(req, 'error', 'Choose an invoice date that is today or earlier (and not before the order was created).');
      res.redirect(`/orders/${orderId}#step-ci-generate`);
      return;
    }
  }

  // Narrow, audited escape hatch for generate()'s own locked-order /
  // out-of-sequence-stage guard (see that method's docblock) — never trust
  // the checkbox alone: re-check the permission server-side (Super Admin
  // bypasses it automatically — req.permissions already has every key set
  // true for one, see sessionAuth.js) and require a real reason before it
  // does anything.
  const overrideRequested = !!req.body.override_gate;
  const overrideReason = String(req.body.override_reason || '').trim();
  let allowOverride = false;
  if (overrideRequested) {
    if (!req.permissions || !req.permissions.edit_locked_data) {
      flash.set(req, 'error', 'You do not have permission to override a locked order or out-of-sequence stage.');
      res.redirect(`/orders/${orderId}`);
      return;
    }
    if (overrideReason.length < 10) {
      flash.set(req, 'error', 'A reason (at least 10 characters) is required to force-generate a document out of sequence or on a locked order.');
      res.redirect(`/orders/${orderId}`);
      return;
    }
    allowOverride = true;
  }

  // QA Round 6, R6-N18: a double click (or several) made one revision each
  // — one generation per order and document type at a time.
  const generationLock = await claimGeneration(orderId, type);
  if (!generationLock) {
    flash.set(req, 'warning', 'This document is being generated right now — wait a moment, then refresh the page.');
    res.redirect(`/orders/${orderId}`);
    return;
  }
  let result;
  try {
    result = await documentGenerationService.generate(orderId, type, user.id, null, generateDocx, allowOverride, documentDate);
  } catch (e) {
    if (e instanceof documentGenerationService.StageGateBlockedError) {
      flash.set(req, 'error', e.message);
      res.redirect(`/orders/${orderId}`);
      return;
    }
    console.error(`[DOCUMENT GENERATION FAILED] order=${orderId} type=${type} —`, e);
    flash.set(req, 'error', 'Document generation failed. Check the server error log for details.');
    res.redirect(`/orders/${orderId}`);
    return;
  } finally {
    await generationLock.release();
  }

  if (allowOverride) {
    await auditLogRepository.log(
      user.id,
      'DOCUMENT_GATE_OVERRIDE',
      'orders',
      orderId,
      'document_type',
      null,
      type,
      overrideReason
    );
  }

  // GATE-01: Stage 1 passes only once the QT is actually *approved* (see
  // reviewWorkflowService.finalizeIfFullyApproved()), not on mere draft
  // generation — Owner Decision #1: "No stage passes until its document is
  // approved." Generating the QT here just creates the draft; it still has
  // to go through review before anything unlocks.

  // QA Round 5, R5-25: a document without its own reference (COOPREP) is named by its order.
  flash.set(req, 'success', result.document_reference
    ? `${type} generated: ${result.document_reference} Rev.${result.revision_number}.`
    : `${await documentLabel(type, null, orderId)} generated — Rev.${result.revision_number}.`);

  // A revision (not a first-ever generation) of an earlier-stage document
  // while later-stage documents already exist means those later documents
  // were built from data that existed before whatever just changed — see
  // downstreamDocumentsAtRisk()'s docblock. Surfacing this only on
  // regeneration, not on normal forward progress through the stages.
  if (result.revision_number > 0) {
    const downstream = await documentGenerationService.downstreamDocumentsAtRisk(orderId, type);
    if (downstream.length > 0) {
      flash.set(
        req,
        'warning',
        `${type} was revised, but this order already has ${downstream.join(', ')} generated from data that existed before this change. Review whether ${downstream.length > 1 ? 'they need' : 'it needs'} to be regenerated too.`
      );
    }
  }

  res.redirect(`/orders/${orderId}`);
}

async function download(req, res) {
  const documentId = parseInt(req.params.documentId, 10);
  const format = String(req.query.format || 'pdf').toLowerCase();

  const document = await documentRepository.find(documentId);
  if (!document) {
    res.status(404).send('Document not found.');
    return;
  }

  // Point 2 follow-up: the internal-only CA Financial Annexure (government
  // export benefits/expenses) is one of many document types this generic
  // route serves, gated at the route level only on the broad download_pdf
  // permission that most staff hold. That's fine for every other type here
  // (BLI/COOPREP/SUPPO/AMD are internal too, but not sensitive financial
  // data) — CAFIN specifically needs the same ca_module_view gate its data
  // already carries everywhere else it's shown, so a staff member without
  // any CA permission can't fetch it just by knowing/guessing its document id.
  // Owner decision (2026-10-28): its own permission, view_cafin — and
  // view_cafin alone is enough for CAFIN (the CA holds it without
  // "Download PDF"); every other document needs download_pdf.
  const requiredKey = document.document_type_code === 'CAFIN' ? 'view_cafin' : 'download_pdf';
  // QA Round 6, Q-R6-2 (D-118): CAFIN also needs the order itself —
  // whoever cannot open the order page cannot download its CAFIN.
  // Owner decision D-214, phase 2: every document needs the order itself
  // (not only CAFIN), and the money it carries must be money this person's
  // department may see (selling: QT/PI/OC/CI/AMD/Debit Note…; purchase:
  // SUPPO; logistics: BLI).
  if (!req.permissions || !req.permissions[requiredKey]
    || (document.order_id && !(await orderAccessService.orderLinkChecker(req.user.id, req.permissions))(document.order_id))
    || !moneyVisibility.canSeeDocument(req.permissions, document.document_type_code)) {
    res.status(403).send('You do not have permission to view this document.');
    return;
  }

  const fileId = format === 'docx' ? document.docx_file_id : document.pdf_file_id;
  if (!fileId) {
    res.status(404).send('That format was not generated for this document.');
    return;
  }

  const file = await fileStoreRepository.find(fileId);
  if (!file || !fs.existsSync(file.server_path)) {
    res.status(404).send('File is missing from storage.');
    return;
  }

  // internal_only files (the content-parity DOCX) are downloadable from
  // here for internal staff use, but are never emailed to the buyer — that
  // boundary is enforced wherever a future "send to buyer" action is
  // built, not here.
  // original_filename is a display name, not a path — a document
  // reference containing "/" (e.g. "SC/AMD/2026/1809001") must not be
  // treated as a path with a directory component, which would silently
  // truncate the header value. Strip slashes/controls instead so the
  // browser always gets the full intended name.
  let safeDownloadName = file.original_filename.replace(/[\\/]/g, '-');
  // eslint-disable-next-line no-control-regex
  safeDownloadName = safeDownloadName.replace(/[\x00-\x1F\x7F"]/g, '');

  res.setHeader('Content-Type', file.mime_type);
  res.setHeader('Content-Disposition', `attachment; filename="${safeDownloadName}"`);
  res.setHeader('Content-Length', String(file.file_size_bytes));
  fs.createReadStream(file.server_path).pipe(res);
}

/**
 * Deletes a mistaken draft document — draft only, never in_review or
 * beyond (those are superseded by a new revision, not deleted). Requires a
 * real reason, same reasonValidator.MIN_LENGTH rule as every other reason
 * field, recorded to the audit trail before the row is gone.
 */
async function deleteDraft(req, res) {
  const orderId = parseInt(req.params.id, 10);
  const documentId = parseInt(req.params.documentId, 10);
  const user = req.user;

  const document = await documentRepository.find(documentId);
  if (!document || document.order_id !== orderId) {
    flash.set(req, 'error', 'Document not found.');
    res.redirect(`/orders/${orderId}`);
    return;
  }
  if (document.status !== 'draft') {
    flash.set(req, 'error', 'Only a draft document can be deleted — this one has moved past draft status.');
    res.redirect(`/orders/${orderId}`);
    return;
  }

  const reason = String(req.body.reason || '').trim();
  const reasonError = reasonValidator.check(reason);
  if (reasonError) {
    flash.set(req, 'error', reasonError);
    res.redirect(`/orders/${orderId}`);
    return;
  }

  const reference = document.document_reference || `${document.document_type_code} Rev.${document.revision_number}`;
  await documentRepository.deleteDraft(documentId);

  await auditLogRepository.log(
    user.id,
    'DOCUMENT_DRAFT_DELETED',
    'orders',
    orderId,
    'document',
    reference,
    null,
    reason
  );

  flash.set(req, 'success', `Draft document ${reference} deleted.`);
  res.redirect(`/orders/${orderId}`);
}

module.exports = { generate, download, deleteDraft };
