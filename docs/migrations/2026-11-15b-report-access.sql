-- 2026-11-15b — Owner decision D-379 (15 Nov 2026): report access per role. Each role gets a level per
-- report (Off / Own / Department / All) and a person can get extra access to one report with a reason.
-- New tables role_report_access and user_report_extras (CREATE TABLE IF NOT EXISTS: a second run changes
-- nothing); the default levels per role (INSERT … WHERE NOT EXISTS by role name: a level already set is
-- never overwritten); the permission "Manage report access" for the MD and the ED (Admin does not get it).
-- No column is added, so no ALTER (owner D-371) and no information_schema / PREPARE guard is needed.
-- Order data is only read. Safe to run twice.
-- Run docs/checks/check_all_migrations.sql first: this file's row says NEEDED until it has run.
SET NAMES utf8mb4;
CREATE TABLE IF NOT EXISTS role_report_access (
  role_id    BIGINT UNSIGNED NOT NULL,
  report_key VARCHAR(40) NOT NULL,
  level      ENUM('off','own','department','all') NOT NULL DEFAULT 'off',
  updated_by BIGINT UNSIGNED NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (role_id, report_key),
  CONSTRAINT fk_role_report_access_role FOREIGN KEY (role_id) REFERENCES roles(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS user_report_extras (
  user_id    BIGINT UNSIGNED NOT NULL,
  report_key VARCHAR(40) NOT NULL,
  level      ENUM('own','department','all') NOT NULL,
  reason     VARCHAR(500) NOT NULL,
  created_by BIGINT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id, report_key),
  CONSTRAINT fk_user_report_extras_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
