/** Clean stage, the staff who hand off, and an empty intake queue. Returns the actors. */
async function setup(demo, { withClient = false } = {}) {
  cleanStage(demo);
  for (const k of ['exec', 'salesmgr', 'accounts', 'fm']) demo.demoStaff(k);
  demo.sql("UPDATE users SET is_active = 0 WHERE email NOT LIKE '%@email.com'");
  // Old dev-test submissions would fill the review queues with odd names: cleared inside the snapshot.
  demo.sql('SET FOREIGN_KEY_CHECKS = 0; DELETE FROM pi_intake_submissions; DELETE FROM client_intake_submissions; SET FOREIGN_KEY_CHECKS = 1');
  let clientId = null;
  if (withClient) {
    clientId = Number(A.php(demo, `
      $exec = $uid('export.executive@email.com');
      $c = $call('createSampleClient', ${JSON.stringify(BUYER.company)}, ${JSON.stringify(`${BUYER.line1}, ${BUYER.postcode} ${BUYER.city}, ${BUYER.country}`)}, $exec, ${JSON.stringify(BUYER_EMAIL)});
      $pdo->prepare('UPDATE clients SET contact_person = ?, is_sample_data = 0 WHERE id = ?')->execute([${JSON.stringify(BUYER.contact)}, $c]);
      echo $c;`).split('\n').pop());
  }
  const actors = { buyer: { ...ACTORS.client(BUYER_EMAIL), label: 'Buyer', cookies: [] } };
  for (const k of ['exec', 'salesmgr', 'accounts', 'fm']) actors[k] = { ...A.ROLES[k], cookies: await demo.staffCookies(k) };
  return { actors, clientId };
}

function clientIdByEmail(demo) { return Number(demo.sql(`SELECT id FROM clients WHERE email = ${demo.q(BUYER_EMAIL)} ORDER BY id DESC LIMIT 1`)); }

/** A CIF order to Rotterdam for the buyer, in US dollars, on the given payment terms. */
function createOrder(demo, clientId, preset = 'Standard — New Buyer') {
  const out = A.php(demo, `
    $exec = $uid('export.executive@email.com');
    $incoterm = null; foreach (App\\Repositories\\LookupRepository::incoterms() as $t) if (strtoupper($t['code']) === 'CIF') $incoterm = $t;
    $currency = null; foreach (App\\Repositories\\LookupRepository::currencies() as $c) if ($c['code'] === 'USD') $currency = $c;
    $port = App\\Repositories\\LookupRepository::ports('loading')[0] ?? null;
    $preset = null; foreach (App\\Repositories\\LookupRepository::paymentPresets() as $p) if ($p['preset_name'] === ${JSON.stringify(preset)}) $preset = $p;
    $order = $call('createSampleOrderCustomLines', ${clientId}, $incoterm, $currency, $port, $preset, $exec, [
      ['description' => 'Black Galaxy Granite Slab', 'dimensions' => '300 x 180 x 2 cm', 'finish' => 'Polished', 'quantity' => '150', 'unit' => 'sqm', 'unit_price' => '48.00', 'hs_code' => '68022390'],
      ['description' => 'Absolute Black Granite Tile', 'dimensions' => '60 x 60 x 1.5 cm', 'finish' => 'Honed', 'quantity' => '300', 'unit' => 'sqm', 'unit_price' => '30.00', 'hs_code' => '68022390'],
    ]);
    $pdo->prepare('UPDATE orders SET port_of_discharge_text = ?, is_sample_data = 0 WHERE id = ?')->execute(['Rotterdam, Netherlands', $order]);
    $pdo->prepare('INSERT IGNORE INTO order_assignees (order_id, user_id, assigned_by) VALUES (?, ?, ?)')->execute([$order, $exec, $exec]);
    if (!empty($preset['requires_md_approval'])) App\\Services\\PaymentTermsApprovalService::approve($order, $uid('md@email.com'));
    echo $order;`);
  return Number(out.split('\n').pop());
}

const ref = (demo, orderId, code) => demo.sql(`SELECT d.document_reference FROM documents d JOIN document_types t ON t.id = d.document_type_id WHERE d.order_id = ${Number(orderId)} AND t.code = ${demo.q(code)} ORDER BY d.id DESC LIMIT 1`);
const last = (out) => out.split('\n').pop().trim();

