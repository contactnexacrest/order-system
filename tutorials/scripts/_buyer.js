/** A set-password link the tutorial knows (the app's own e-mailed token is random and never stored in clear). */
function setPasswordLink(demo, clientId) {
  const raw = require('crypto').randomBytes(32).toString('hex');
  const hash = require('crypto').createHash('sha256').update(raw).digest('hex');
  A.php(demo, `App\\Repositories\\ClientPasswordResetTokenRepository::create(${clientId}, '${hash}', date('Y-m-d H:i:s', time() + 72 * 3600), null);`);
  return `/client/set-password/${raw}`;
}

